let idioma = 'es';

function t(key) {
    const tabla = I18N[idioma] || I18N.es;
    return tabla[key] != null ? tabla[key] : (I18N.es[key] != null ? I18N.es[key] : key);
}

function tFmt(key, params) {
    let s = t(key);
    for (const k in params) s = s.replace('{' + k + '}', params[k]);
    return s;
}